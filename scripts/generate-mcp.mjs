#!/usr/bin/env node
import { cp, lstat, mkdir, mkdtemp, readFile, readdir, realpath, rename, rm } from "node:fs/promises";
import { basename, dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { spawn } from "node:child_process";
import { findUnpinnedImports, importSpecifiers, validateImportMap } from "./check-edge-function-pins.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const SDK = "npm:@lovable.dev/mcp-js@3.4.0";

export async function assertSafeGenerationPath(root, target) {
  root = resolve(root);
  target = resolve(target);
  const within = (base, path) => {
    const rel = relative(base, path);
    return rel !== ".." && !rel.startsWith(`..${sep}`) && !isAbsolute(rel);
  };
  if (relative(root, target) === "" || !within(root, target)) throw new Error(`Generation path is root or outside root: ${target}`);
  if ((await lstat(root)).isSymbolicLink()) throw new Error(`Generation root is a link/junction: ${root}`);
  const physicalRoot = await realpath(root);
  let current = root;
  for (const part of relative(root, target).split(sep)) {
    current = join(current, part);
    let stat;
    try {
      stat = await lstat(current);
    } catch (error) {
      if (error.code === "ENOENT") break;
      throw error;
    }
    if (stat.isSymbolicLink()) throw new Error(`Generation path is a link/junction: ${current}`);
    if (!within(physicalRoot, await realpath(current))) throw new Error(`Resolved generation path outside root: ${current}`);
  }
  // Inspect descendants as well: recursive removal must not traverse links.
  async function inspect(path) {
    let stat;
    try { stat = await lstat(path); } catch (error) {
      if (error.code === "ENOENT") return;
      throw error;
    }
    if (stat.isSymbolicLink()) throw new Error(`Generation tree contains a link/junction: ${path}`);
    if (!within(physicalRoot, await realpath(path))) throw new Error(`Resolved generation tree outside root: ${path}`);
    if (stat.isDirectory()) for (const name of await readdir(path)) await inspect(join(path, name));
  }
  await inspect(target);
  return target;
}

async function safeRename(root, from, to) {
  from = await assertSafeGenerationPath(root, from);
  to = await assertSafeGenerationPath(root, to);
  await rename(from, to);
}

async function safeRemove(root, target) {
  target = await assertSafeGenerationPath(root, target);
  await rm(target, { recursive: true, force: true });
}

export function validateArtifacts({ index, deno }, projectRef) {
  if (!/^[a-z]{20}$/.test(projectRef)) throw new Error("Invalid project ref");
  if (!index.startsWith("// AUTO-GENERATED by @lovable.dev/mcp-js")) throw new Error("Missing official generation banner");
  // Fail closed on machine paths, even in generated comments or string literals.
  const machinePath = /\b[a-z]:[\\/]|node_modules|file:\/\/|\/(?:Users|home|tmp)\//i;
  if (machinePath.test(index)) {
    const offender = importSpecifiers(index).find(({ spec }) => machinePath.test(spec));
    throw new Error(`Machine path in MCP artifact${offender ? `: ${offender.spec}` : ""}`);
  }
  if (findUnpinnedImports(index).length) throw new Error("Unpinned MCP import");
  if (deno && validateImportMap(deno).length) throw new Error("Unpinned MCP import map");
  const mappings = deno?.imports ?? {};
  for (const { spec } of importSpecifiers(index)) {
    const target = mappings[spec] ?? spec;
    if (!/^(npm:|node:)/.test(target) || /\b[a-z]:[\\/]|node_modules/i.test(target)) throw new Error(`Non-portable MCP import: ${spec}`);
  }
  for (const mapping of [mappings, ...Object.values(deno?.scopes ?? {})]) {
    for (const target of Object.values(mapping)) {
      if (typeof target !== "string" || !/^npm:/.test(target) || /\b[a-z]:[\\/]|node_modules/i.test(target)) throw new Error("Non-portable import map");
    }
  }
  const specs = importSpecifiers(index).map(({ spec }) => mappings[spec] ?? spec);
  if (!specs.includes(SDK) || !specs.includes(`${SDK}/stacks/supabase`) || !/Deno\.serve\(createSupabaseHandler\(/.test(index)) throw new Error("Missing official Supabase handler");
  const refDeclaration = new RegExp(`(?:var|const) projectRef = ["']${projectRef}["'];`);
  if (!refDeclaration.test(index) || !index.includes('issuer: `https://${projectRef}.supabase.co/auth/v1`')) throw new Error("Incorrect OAuth issuer");
  if (!/acceptedAudiences:\s*["']authenticated["']/.test(index)) throw new Error("Incorrect OAuth audience");
  if (!/acceptResourceClaim:\s*false\b/.test(index)) throw new Error("OAuth resource-claim fallback must be disabled");
}

async function readArtifacts(directory) {
  const names = await readdir(directory);
  if (names.some((name) => !["index.ts", "deno.json"].includes(name))) throw new Error("Unexpected MCP output files");
  const denoSource = names.includes("deno.json") ? await readFile(join(directory, "deno.json"), "utf8") : undefined;
  return {
    index: await readFile(join(directory, "index.ts"), "utf8"),
    deno: denoSource === undefined ? undefined : JSON.parse(denoSource),
    denoSource,
  };
}

// The child gets only public generation input and OS necessities. Neither Vite's
// env loader nor the official plugin can read the real project's .env files.
async function officialEmit(stage, projectRef) {
  const env = { VITE_SUPABASE_PROJECT_ID: projectRef };
  for (const key of ["SystemRoot", "WINDIR", "PATH", "TEMP", "TMP", "HOME", "TMPDIR"]) {
    if (process.env[key]) env[key] = process.env[key];
  }
  await new Promise((accept, reject) => {
    const child = spawn(process.execPath, [fileURLToPath(import.meta.url), "--emit", stage], { env, stdio: "inherit" });
    child.once("error", reject);
    child.once("exit", (code) => code === 0 ? accept() : reject(new Error(`Official MCP plugin failed (${code})`)));
  });
}

export async function generateMcp({ root = ROOT, projectRef, emit = officialEmit }) {
  root = resolve(root);
  await assertSafeGenerationPath(root, join(root, "supabase/config.toml"));
  const config = await readFile(join(root, "supabase/config.toml"), "utf8");
  const configuredRef = /^project_id\s*=\s*"([a-z]{20})"\s*$/m.exec(config)?.[1];
  if (!configuredRef || configuredRef !== projectRef) throw new Error("Project ref must match supabase/config.toml");
  const canonical = join(root, "supabase/functions/mcp");
  // Exclusive lock prevents concurrent publishers from replacing each other's work.
  const lock = join(root, "supabase/functions/.mcp-generation-lock");
  await assertSafeGenerationPath(root, canonical);
  await assertSafeGenerationPath(root, lock);
  await mkdir(lock);
  let stage;
  try {
    stage = await mkdtemp(join(root, ".mcp-generation-"));
    await assertSafeGenerationPath(root, stage);
    await assertSafeGenerationPath(root, join(root, "src/lib/mcp"));
    await assertSafeGenerationPath(root, join(root, "package.json"));
    await mkdir(join(stage, "src/lib"), { recursive: true });
    await cp(join(root, "src/lib/mcp"), join(stage, "src/lib/mcp"), { recursive: true });
    await cp(join(root, "package.json"), join(stage, "package.json"));
    await emit(stage, projectRef);
    const output = join(stage, "supabase/functions/mcp");
    await assertSafeGenerationPath(root, output);
    validateArtifacts(await readArtifacts(output), projectRef);
    // Require a byte-identical second official emission before publishing.
    const first = await readArtifacts(output);
    await emit(stage, projectRef);
    await assertSafeGenerationPath(root, output);
    const second = await readArtifacts(output);
    validateArtifacts(second, projectRef);
    if (JSON.stringify(first) !== JSON.stringify(second)) throw new Error("Non-deterministic official MCP output");
    const names = await readdir(canonical);
    if (names.some((name) => !["index.ts", "deno.json"].includes(name))) throw new Error("Unexpected canonical files; refusing replacement");
    const backup = join(lock, "previous");
    await safeRename(root, canonical, backup);
    try {
      // Same-volume directory rename publishes index + optional import map together.
      await safeRename(root, output, canonical);
    } catch (error) {
      await safeRename(root, backup, canonical);
      throw error;
    }
    await safeRemove(root, backup);
  } finally {
    if (stage) await safeRemove(root, stage);
    // Preserve the backup/lock after an interrupted or failed rollback for recovery.
    await assertSafeGenerationPath(root, lock);
    if (!(await readdir(lock)).length) await safeRemove(root, lock);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv[2] === "--emit") {
    const stage = resolve(process.argv[3] ?? ".");
    if (dirname(stage) !== resolve(ROOT) || !basename(stage).startsWith(".mcp-generation-")) throw new Error("Internal emission requires an isolated generation directory");
    await assertSafeGenerationPath(ROOT, stage);
    const { resolveConfig } = await import("vite");
    const { mcpPlugin } = await import("@lovable.dev/mcp-js/stacks/supabase/vite");
    await resolveConfig({ root: stage, configFile: false, envFile: false, plugins: [mcpPlugin()] }, "build", "production");
  } else {
    if (process.argv[2] !== "--project-ref" || process.argv.length !== 4) throw new Error("Usage: npm run generate:mcp -- --project-ref <public-project-ref>");
    await generateMcp({ projectRef: process.argv[3] });
    console.log("Official MCP artifacts generated, validated twice and published. No deploy performed.");
  }
}
