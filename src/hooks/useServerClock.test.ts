import { act, renderHook } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
const { getServerTime } = vi.hoisted(() => ({ getServerTime: vi.fn() }));
vi.mock('@/services/serverClockApi', () => ({ serverClockApi: { getServerTime } }));
import { useServerClock } from '@/hooks/useServerClock';
beforeEach(() => { vi.useFakeTimers(); vi.resetAllMocks(); });
afterEach(() => { vi.useRealTimers(); vi.restoreAllMocks(); });
it.each([-3600000, 3600000])('uses midpoint and survives OS clock drift (skew=%s)', async skew => {
  const server = Date.parse('2026-01-01T00:00:00Z');
  vi.setSystemTime(server + skew);
  let resolve!: (n: number) => void;
  getServerTime.mockReturnValue(new Promise<number>(r => { resolve = r; }));
  const { result } = renderHook(() => useServerClock('a'));
  await act(async () => { vi.advanceTimersByTime(200); resolve(server + 100); });
  expect(result.current.status).toBe('synced');
  expect(result.current.now()).toBe(server + 200);
  vi.setSystemTime(server + 86400000);
  act(() => vi.advanceTimersByTime(1000));
  expect(result.current.now()).toBe(server + 1200);
});
it('ignores stale sessions and out-of-order revalidations', async () => {
  const resolvers: Array<(n: number) => void> = [];
  getServerTime.mockImplementation(() => new Promise<number>(r => resolvers.push(r)));
  const { result, rerender } = renderHook(({ key }) => useServerClock(key), { initialProps: { key: 'a' } });
  rerender({ key: 'b' });
  await act(async () => { resolvers[1](10000); });
  expect(result.current.now()).toBe(10000);
  await act(async () => { resolvers[0](9999999); });
  expect(result.current.now()).toBe(10000);
  await act(async () => { window.dispatchEvent(new Event('online')); });
  vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('visible');
  await act(async () => { document.dispatchEvent(new Event('visibilitychange')); });
  await act(async () => { resolvers[3](20000); resolvers[2](30000); });
  expect(result.current.now()).toBe(20000);
});
it('declares monotonic local fallback after RPC failure and revalidates online', async () => {
  getServerTime.mockRejectedValue(new Error('offline'));
  const { result } = renderHook(() => useServerClock('a'));
  await act(async () => {});
  expect(result.current.status).toBe('fallback');
  const now = result.current.now();
  vi.setSystemTime(Date.now() + 999999);
  act(() => vi.advanceTimersByTime(1000));
  expect(result.current.now()).toBe(now + 1000);
  getServerTime.mockResolvedValue(now + 5000);
  await act(async () => { window.dispatchEvent(new Event('online')); });
  expect(result.current.status).toBe('synced');
});
it('bounds a stalled RPC and ignores its late completion after timeout', async () => {
  let resolve!: (n: number) => void;
  getServerTime.mockReturnValue(new Promise<number>(r => { resolve = r; }));
  const { result } = renderHook(() => useServerClock('a'));
  await act(async () => { await vi.advanceTimersByTimeAsync(5000); });
  expect(result.current.status).toBe('fallback');
  const time = result.current.now();
  await act(async () => { resolve(1); });
  expect(result.current.now()).toBe(time);
});
it('handles a synchronous RPC throw without cleaning up an uninitialized timeout', async () => {
  getServerTime.mockImplementation(() => { throw new Error('RPC unavailable'); });
  const clear = vi.spyOn(globalThis, 'clearTimeout');
  const { result } = renderHook(() => useServerClock('a'));
  await act(async () => {});
  expect(result.current.status).toBe('fallback');
  expect(clear).not.toHaveBeenCalledWith(undefined);
  getServerTime.mockResolvedValue(10000);
  await act(async () => { window.dispatchEvent(new Event('online')); });
  expect(result.current.status).toBe('synced');
});
